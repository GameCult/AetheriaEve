import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = resolve(fileURLToPath(import.meta.url), "..", "..");
const sourcePath = resolve(webRoot, "..", "Packages", "org.gamecult.aetheria.state", "Runtime", "AetheriaRuntimeDaemonDocuments.cs");
const outputPath = resolve(webRoot, "Electron", "aetheria-daemon-command-codec.ts");
const source = readFileSync(sourcePath, "utf8");
const check = process.argv.includes("--check");

const commandBody = readBody("class AetheriaRuntimeDaemonCommandDocument");
const enumBody = readBody("enum AetheriaRuntimeDaemonCommandKinds");
const classIndex = source.indexOf("class AetheriaRuntimeDaemonCommandDocument");
const classPrefix = source.slice(Math.max(0, classIndex - 500), classIndex);
const schemaMatch = /\[CultDocument\("[^"]+",\s*"([^"]+)"\)\]/u.exec(classPrefix);
if (!schemaMatch)
  throw new Error("AetheriaRuntimeDaemonCommandDocument has no CultDocument schema.");

const slots = [...commandBody.matchAll(/\[Key\((\d+)\)\][\s\S]*?public\s+([A-Za-z0-9_<>,.?\[\]\s]+)\s+([A-Za-z_][A-Za-z0-9_]*)\s*\{\s*get;\s*set;\s*\}/gu)]
  .map(match => ({ key: Number.parseInt(match[1], 10), type: match[2].trim(), name: lowerFirst(match[3]) }))
  .sort((left, right) => left.key - right.key);
if (slots.length === 0)
  throw new Error("AetheriaRuntimeDaemonCommandDocument has no MessagePack slots.");

const enumEntries = [];
let nextEnumValue = 0;
for (const rawLine of enumBody.split(/\r?\n/u)) {
  const line = rawLine.replace(/\/\/.*$/u, "").trim().replace(/,$/u, "");
  if (!line)
    continue;
  const match = /^([A-Za-z_][A-Za-z0-9_]*)(?:\s*=\s*(-?\d+))?$/u.exec(line);
  if (!match)
    continue;
  const value = match[2] === undefined ? nextEnumValue : Number.parseInt(match[2], 10);
  enumEntries.push({ name: lowerFirst(match[1]), value });
  nextEnumValue = value + 1;
}

const slotLines = slots.map(slot => `  ${slot.name}: ${slot.key}, // ${slot.type}`).join("\n");
const enumLines = enumEntries.map(entry => `  ${entry.name}: ${entry.value},`).join("\n");
const arrayLength = Math.max(...slots.map(slot => slot.key)) + 1;
const generated = `// <auto-generated />
// Slot numbers, schema id, and enum values come from AetheriaRuntimeDaemonDocuments.cs.
// Semantic operation helpers are deliberately small and covered by the C# <-> TypeScript wire witness.

export const AetheriaDaemonCommandSchema = ${JSON.stringify(schemaMatch[1])} as const;

export const AetheriaRuntimeDaemonCommandKinds = {
${enumLines}
} as const;

export const aetheriaRuntimeDaemonCommandDocumentSlots = {
${slotLines}
} as const;

export type AetheriaRuntimeSetMoveVectorRequest = {
  actorEntityKey: string;
  directionX: number;
  directionY: number;
  scalar: number;
  observedFrameId?: number;
};

export type AetheriaRuntimeSetTargetRequest = {
  actorEntityKey: string;
  targetEntityKey: string;
  observedFrameId?: number;
};

export function encodeSetMoveVectorCommand(
  commandId: string,
  issuedAtUtc: string,
  runtimeId: string,
  request: AetheriaRuntimeSetMoveVectorRequest,
): unknown[] {
  const command = createBaseCommand(commandId, issuedAtUtc, runtimeId, request.actorEntityKey, request.observedFrameId);
  command[aetheriaRuntimeDaemonCommandDocumentSlots.kind] = AetheriaRuntimeDaemonCommandKinds.setMoveVector;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.directionX] = request.directionX;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.directionY] = request.directionY;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.scalarValue] = Math.min(1, Math.max(0, request.scalar));
  command[aetheriaRuntimeDaemonCommandDocumentSlots.claimKind] = "movement";
  return command;
}

export function encodeSetTargetCommand(
  commandId: string,
  issuedAtUtc: string,
  runtimeId: string,
  request: AetheriaRuntimeSetTargetRequest,
): unknown[] {
  const command = createBaseCommand(commandId, issuedAtUtc, runtimeId, request.actorEntityKey, request.observedFrameId);
  command[aetheriaRuntimeDaemonCommandDocumentSlots.kind] = AetheriaRuntimeDaemonCommandKinds.setTarget;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.targetEntityKey] = request.targetEntityKey;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.claimKind] = "targeting";
  return command;
}

function createBaseCommand(
  commandId: string,
  issuedAtUtc: string,
  runtimeId: string,
  actorEntityKey: string,
  observedFrameId?: number,
): unknown[] {
  const command = new Array<unknown>(${arrayLength}).fill(null);
  command[aetheriaRuntimeDaemonCommandDocumentSlots.schema] = AetheriaDaemonCommandSchema;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.commandId] = commandId;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.clientId] = runtimeId;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.issuedAtUtc] = issuedAtUtc;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.sessionId] = "local";
  command[aetheriaRuntimeDaemonCommandDocumentSlots.observedFrameId] = observedFrameId ?? -1;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.kind] = AetheriaRuntimeDaemonCommandKinds.none;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.actorEntityKey] = actorEntityKey;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.targetEntityKey] = "";
  command[aetheriaRuntimeDaemonCommandDocumentSlots.targetZoneIndex] = -1;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.equipmentIndex] = -1;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.behaviorIndex] = -1;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.weaponGroup] = -1;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.positionX] = 0;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.positionY] = 0;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.positionZ] = 0;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.directionX] = 0;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.directionY] = 0;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.scalarValue] = 0;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.textValue] = "";
  command[aetheriaRuntimeDaemonCommandDocumentSlots.authorRuntimeId] = runtimeId;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.subjectKey] = actorEntityKey;
  command[aetheriaRuntimeDaemonCommandDocumentSlots.claimKind] = "";
  return command;
}
`;

if (check) {
  if (readExisting(outputPath) !== generated) {
    console.error("Aetheria command codec is stale. Run `npm run generate:rts-bindings`.");
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, generated, "utf8");
}

function readBody(declaration) {
  const declarationIndex = source.indexOf(declaration);
  if (declarationIndex < 0)
    throw new Error(`Could not find ${declaration}.`);
  const openIndex = source.indexOf("{", declarationIndex);
  let depth = 0;
  for (let index = openIndex; index < source.length; index += 1) {
    if (source[index] === "{") depth += 1;
    if (source[index] === "}") {
      depth -= 1;
      if (depth === 0) return source.slice(openIndex + 1, index);
    }
  }
  throw new Error(`Could not read ${declaration}.`);
}

function readExisting(path) {
  try { return readFileSync(path, "utf8"); } catch { return ""; }
}

function lowerFirst(value) {
  return value.length === 0 ? value : value[0].toLowerCase() + value.slice(1);
}
